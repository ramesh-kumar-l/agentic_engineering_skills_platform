"""Evaluation harness for the codebase-intelligence skill.

Implements the Skill -> Evaluation Dataset -> Runtime -> Execution -> Scoring
-> Report pipeline from project-memory-bank/05-evaluation-framework.md, scoped
to this one skill (per that file: "do not over-engineer this before there's
evidence it's needed" — no generic multi-skill harness yet).

Correctness/Completeness/Efficiency are scored automatically by diffing actual
output against hand-authored ground truth. Safety/Relevance/Explainability are
NOT scored here — the framework requires those never be self-evaluated by the
model alone, so they are left for human review in RESULTS.md.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent
ENGINE_ROOT = HARNESS_DIR.parents[1] / "skills" / "codebase-intelligence"
sys.path.insert(0, str(ENGINE_ROOT))

from engine.report import build_report  # noqa: E402


def summarize(report) -> dict:
    return {
        "file_count": report.file_count,
        "language_breakdown": report.language_breakdown,
        "entry_point_paths": sorted(ep.path for ep in report.entry_points),
        "internal_edges": sorted([[e.source, e.target] for e in report.dependency_graph.edges]),
        "external_dependency_names": sorted(d.name for d in report.external_dependencies),
        "excluded_dir_count": report.excluded_dir_count,
    }


def score_case(actual: dict, expected: dict) -> tuple[int, list[str]]:
    mismatches: list[str] = []
    for key, expected_value in expected.items():
        actual_value = actual.get(key)
        normalized_actual = sorted(actual_value) if isinstance(actual_value, list) else actual_value
        normalized_expected = sorted(expected_value) if isinstance(expected_value, list) else expected_value
        if normalized_actual != normalized_expected:
            mismatches.append(f"{key}: expected {expected_value!r}, got {actual_value!r}")
    total_fields = len(expected)
    correctness = 5 if not mismatches else max(0, 5 - len(mismatches) * (5 // max(total_fields, 1) or 1))
    return correctness, mismatches


def run() -> None:
    fixtures_dir = HARNESS_DIR / "fixtures"
    expected_dir = HARNESS_DIR / "expected"
    results_lines = ["# Codebase Intelligence — Evaluation Results", ""]
    results_lines.append("Generated by `run_evaluation.py`. Correctness/Completeness/Efficiency are")
    results_lines.append("scored automatically against hand-authored ground truth. Safety/Relevance/")
    results_lines.append("Explainability require human review and are NOT scored here (see")
    results_lines.append("`project-memory-bank/05-evaluation-framework.md`: the model must never be")
    results_lines.append("the sole evaluator of itself for critical claims).")
    results_lines.append("")

    all_correct = True
    for fixture_dir in sorted(fixtures_dir.iterdir()):
        if not fixture_dir.is_dir():
            continue
        name = fixture_dir.name
        expected_path = expected_dir / f"{name}.expected.json"
        if not expected_path.exists():
            continue
        expected = json.loads(expected_path.read_text(encoding="utf-8"))

        start = time.perf_counter()
        report = build_report(fixture_dir)
        elapsed_ms = (time.perf_counter() - start) * 1000

        actual = summarize(report)
        correctness, mismatches = score_case(actual, expected)
        efficiency = 5 if elapsed_ms < 500 else 3 if elapsed_ms < 2000 else 1
        completeness = 5 if not mismatches else 3

        if mismatches:
            all_correct = False

        results_lines.append(f"## {name}")
        results_lines.append(f"- Correctness: {correctness}/5")
        results_lines.append(f"- Completeness: {completeness}/5")
        results_lines.append(f"- Efficiency: {efficiency}/5 ({elapsed_ms:.1f}ms)")
        results_lines.append("- Safety: _human review required_")
        results_lines.append("- Relevance: _human review required_")
        results_lines.append("- Explainability: _human review required_")
        if mismatches:
            results_lines.append("- Mismatches:")
            for m in mismatches:
                results_lines.append(f"  - {m}")
        else:
            results_lines.append("- Mismatches: none")
        results_lines.append("")

    results_lines.append("## Summary")
    results_lines.append(
        "All automated (Correctness/Completeness) checks passed." if all_correct
        else "One or more cases had mismatches — see above. Do not treat this skill as"
             " VERIFIED until resolved."
    )
    results_lines.append("")
    results_lines.append(
        "This is the first real evidence recorded against "
        "`project-memory-bank/16-assumptions-and-validation.md` (assumptions A2, A3, A5)."
        " It validates deterministic correctness on synthetic fixtures only — it is"
        " NOT evidence of real-world engineer usefulness (see project thesis)."
    )

    (HARNESS_DIR / "RESULTS.md").write_text("\n".join(results_lines), encoding="utf-8")
    print(f"wrote {HARNESS_DIR / 'RESULTS.md'}")
    if not all_correct:
        sys.exit(1)


if __name__ == "__main__":
    run()
